for (const [loc, ov] of Object.entries(T)) {
  const p = path.join(__dirname, '..', 'messages', `${loc}.json`)
  const m = JSON.parse(fs.readFileSync(p, 'utf8'))

  if (!m.dashboard) m.dashboard = {}
  if (!m.dashboard.home) m.dashboard.home = {}
  if (!m.dashboard.home.ov) m.dashboard.home.ov = {}
  Object.assign(m.dashboard.home.ov, ov)

  fs.writeFileSync(p, JSON.stringify(m, null, 2) + '\n', 'utf8')
  console.log(`${loc}: +dashboard.home.ov.* (${Object.keys(ov).length} keys)`)
}
