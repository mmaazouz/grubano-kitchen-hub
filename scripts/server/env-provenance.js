/* ─────────────────────────────────────────────────────────────────────────────
   scripts/server/env-provenance.js — PURE helper. Required (a) by the preamble that
   scripts/fix-server.js injects at the top of the DEPLOYED Passenger entry
   (.next/standalone/server.js, generated by Next — the root server.js of the repo is NOT
   what the deploy ships) and (b) by the preflight operator. It answers, for a fixed list
   of SECRET/CONFIG keys and WITHOUT ever touching a value:

     • was the key ALREADY in process.env BEFORE Next loads any env file?  (hosting-injected:
       cPanel Node.js selector / Passenger / CloudLinux — or the shell for a terminal run)
     • which env file(s) define it, under the loader Next really uses (@next/env = dotenv):
         order  .env.production.local → .env.local → .env.production → .env  (FIRST FILE that
         defines a key wins; a key already in process.env is NEVER overridden);
         within ONE file dotenv semantics: `export KEY=…` accepted, leading whitespace
         accepted, spaces around `=` accepted, quotes stripped, `# comment` after an unquoted
         value dropped, LAST occurrence wins;
     • are the pre-existing value and the file-merged value EQUAL?  (boolean, in-process)
     • which source is EFFECTIVE for the process.

   Output = key NAMES + BOOLEANS + file names + occurrence COUNTS only. No value, no length,
   no prefix, no hash, no fingerprint. Safe to write to tmp/env-provenance.json and to print.
   ───────────────────────────────────────────────────────────────────────────── */

const NEXT_ENV_FILES = ['.env.production.local', '.env.local', '.env.production', '.env']

// dotenv 16.3.1 line grammar (the one bundled in @next/env) — ported verbatim.
const DOTENV_LINE = /(?:^|^)\s*(?:export\s+)?([\w.-]+)(?:\s*=\s*?|:\s+?)(\s*'(?:\\'|[^'])*'|\s*"(?:\\"|[^"])*"|\s*`(?:\\`|[^`])*`|[^#\r\n]+)?\s*(?:#.*)?(?:$|$)/gm

/** dotenv.parse — LAST occurrence wins; returns { key: value } (values are consumed in-process only). */
function parseEnvDotenv(text) {
  const out = {}
  let src = String(text || '').replace(/\r\n?/gm, '\n')
  let m
  DOTENV_LINE.lastIndex = 0
  while ((m = DOTENV_LINE.exec(src)) != null) {
    const key = m[1]
    let v = (m[2] || '').trim()
    const q = v[0]
    v = v.replace(/^(['"`])([\s\S]*)\1$/gm, '$2')
    if (q === '"') v = v.replace(/\\n/g, '\n').replace(/\\r/g, '\r')
    out[key] = v
  }
  return out
}
/** Occurrences of `key` in one file under dotenv line grammar (count only). */
function countDotenvOccurrences(text, key) {
  let n = 0, m
  const src = String(text || '').replace(/\r\n?/gm, '\n')
  const re = new RegExp(DOTENV_LINE.source, 'gm')
  while ((m = re.exec(src)) != null) if (m[1] === key) n++
  return n
}
/** The repo's ROOT server.js loader (NOT deployed — kept for the divergence diagnosis):
 *  strict `^KEY=value$` on the raw line, FIRST occurrence wins, one quote pair stripped, trim. */
function parseEnvStrict(text) {
  const out = {}
  for (const line of String(text || '').split(/\r?\n/)) {
    const m = line.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/)
    if (m && !(m[1] in out)) out[m[1]] = m[2].replace(/^["']|["']$/g, '').trim()
  }
  return out
}

/**
 * Merge env files the way @next/env does (production mode): first file defining a key
 * wins; process.env (pre-existing) always wins over every file.
 * @param {Record<string,string>} textsByFile  raw contents keyed by file name (missing = absent)
 * @returns {{ merged: Record<string,string>, definedIn: Record<string,string[]> }}
 */
function mergeNextEnvFiles(textsByFile) {
  const merged = {}
  const definedIn = {}
  for (const f of NEXT_ENV_FILES) {
    if (typeof textsByFile[f] !== 'string') continue
    const parsed = parseEnvDotenv(textsByFile[f])
    for (const k of Object.keys(parsed)) {
      ;(definedIn[k] = definedIn[k] || []).push(f)
      if (typeof merged[k] === 'undefined') merged[k] = parsed[k]
    }
  }
  return { merged, definedIn }
}

/**
 * @param {Record<string, string|undefined>} preEnv       snapshot of process.env BEFORE any env file is loaded
 * @param {Record<string, string>} textsByFile           raw env file contents present in the app dir
 * @param {string[]} keys
 */
function computeProvenance(preEnv, textsByFile, keys) {
  const { merged, definedIn } = mergeNextEnvFiles(textsByFile || {})
  const filesPresent = NEXT_ENV_FILES.filter((f) => typeof (textsByFile || {})[f] === 'string')
  const out = {}
  for (const k of keys) {
    const pre = preEnv ? preEnv[k] : undefined
    const presentBefore = typeof pre !== 'undefined'
    const files = definedIn[k] || []
    const presentInFiles = files.length > 0
    const occurrences = {}
    for (const f of files) occurrences[f] = countDotenvOccurrences(textsByFile[f], k)
    let equal = null
    if (presentBefore && presentInFiles) equal = String(pre) === merged[k]
    out[k] = {
      presentBeforeEnvLoad: presentBefore,
      presentInEnvFiles: presentInFiles,
      definedIn: files,
      occurrences,
      equalProcessVsFiles: equal,
      effectiveSource: presentBefore ? 'process' : (presentInFiles ? files[0] : 'none'),
    }
  }
  return {
    at: new Date().toISOString(),
    loader: '@next/env (dotenv): files .env.production.local > .env.local > .env.production > .env ; first file wins ; last occurrence in a file wins ; pre-existing process.env never overridden',
    filesPresent,
    keys: out,
  }
}

/** Defensive: refuse to serialise anything that looks like a value. */
function assertNoValues(report) {
  const allowedStr = new Set(['at', 'loader', 'effectiveSource'])
  const allowedKeys = new Set(['at', 'loader', 'filesPresent', 'keys', 'presentBeforeEnvLoad', 'presentInEnvFiles', 'definedIn', 'occurrences', 'equalProcessVsFiles', 'effectiveSource'])
  const isFileName = (s) => NEXT_ENV_FILES.includes(s)
  const walk = (o, ctx) => {
    if (o === null || typeof o !== 'object') return
    if (Array.isArray(o)) { for (const v of o) if (typeof v !== 'string' || !isFileName(v)) throw new Error('env-provenance: unexpected array item'); return }
    for (const [k, v] of Object.entries(o)) {
      if (ctx === 'keys') { if (!/^[A-Z_][A-Z0-9_]*$/.test(k)) throw new Error('env-provenance: unexpected key name'); walk(v, 'entry'); continue }
      if (ctx === 'occurrences') { if (!isFileName(k) || typeof v !== 'number') throw new Error('env-provenance: bad occurrences'); continue }
      if (!allowedKeys.has(k)) throw new Error('env-provenance: unexpected field ' + k)
      if (typeof v === 'string' && !allowedStr.has(k)) throw new Error('env-provenance: string value not allowed under ' + k)
      if (k === 'effectiveSource' && !(v === 'process' || v === 'none' || isFileName(v))) throw new Error('env-provenance: bad effectiveSource')
      walk(v, k === 'keys' ? 'keys' : (k === 'occurrences' ? 'occurrences' : 'x'))
    }
  }
  walk(report, 'root')
  return report
}

