/** Read the env files present in `dir` (raw text, in-process only). */
function readNextEnvFiles(fs, path, dir) {
  const texts = {}
  for (const f of NEXT_ENV_FILES) {
    try { texts[f] = fs.readFileSync(path.join(dir, f), 'utf8') } catch (_) { /* absent */ }
  }
  return texts
}

