for (const [loc, kv] of Object.entries(T)) {
  const p = path.join(__dirname, '..', 'messages', `${loc}.json`)
  const m = JSON.parse(fs.readFileSync(p, 'utf8'))

  if (!m.eat) m.eat = {}
  if (!m.eat.reservation) m.eat.reservation = {}
  Object.assign(m.eat.reservation, kv.eat)

  if (!m.tables) m.tables = {}
  if (!m.tables.deposit) m.tables.deposit = {}
  Object.assign(m.tables.deposit, kv.tables)

  fs.writeFileSync(p, JSON.stringify(m, null, 2) + '\n', 'utf8')
  console.log(`${loc}: +eat.reservation.* (${Object.keys(kv.eat).length}) +tables.deposit.* (${Object.keys(kv.tables).length})`)
}
