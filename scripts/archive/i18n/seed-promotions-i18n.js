const messagesDir = path.join(__dirname, '..', 'messages')
for (const [locale, dict] of Object.entries(KEYS)) {
  const file = path.join(messagesDir, `${locale}.json`)
  const json = JSON.parse(fs.readFileSync(file, 'utf8'))
  json.promotions = { ...(json.promotions ?? {}), ...dict }
  json.dashboard = json.dashboard ?? {}
  json.dashboard.sidebar = { ...(json.dashboard.sidebar ?? {}), navPromotions: NAV[locale] }
  fs.writeFileSync(file, JSON.stringify(json, null, 2) + '\n', 'utf8')
  console.log(`${locale}.json — promotions: ${Object.keys(dict).length} keys + navPromotions`)
}
console.log('Done.')
