for (const loc of ['fr', 'en', 'es', 'it', 'ar']) {
  const file = path.join(__dirname, '..', 'messages', `${loc}.json`)
  const m = JSON.parse(fs.readFileSync(file, 'utf8'))

  if (!m.creators) m.creators = {}
  m.creators.allergens  = Object.assign(m.creators.allergens  ?? {}, KEYS[loc].allergens)
  m.creators.difficulty = Object.assign(m.creators.difficulty ?? {}, KEYS[loc].difficulty)
  if (!m.creators.editor) m.creators.editor = {}
  Object.assign(m.creators.editor, KEYS[loc].editor)

  if (!m.menu) m.menu = {}
  if (!m.menu.adopt) m.menu.adopt = {}
  Object.assign(m.menu.adopt, KEYS[loc].adopt)
  m.menu.sheet = Object.assign(m.menu.sheet ?? {}, KEYS[loc].sheet)

  if (!m.chef) m.chef = {}
  Object.assign(m.chef, KEYS[loc].chef)

  fs.writeFileSync(file, JSON.stringify(m, null, 2) + '\n', 'utf8')
  console.log(`[seed-dish-sheet-i18n] ${loc}.json OK`)
}
