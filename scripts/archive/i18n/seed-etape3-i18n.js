for (const [loc, kv] of Object.entries(T)) {
  const p = path.join(__dirname, '..', 'messages', `${loc}.json`)
  const m = JSON.parse(fs.readFileSync(p, 'utf8'))
  if (!m.premium) m.premium = {}
  Object.assign(m.premium, {
    order:     { ...(m.premium.order ?? {}),     ...kv.order },
    mysession: { ...(m.premium.mysession ?? {}), ...kv.mysession },
    closure:   { ...(m.premium.closure ?? {}),   ...kv.closure },
    history:   { ...(m.premium.history ?? {}),   ...kv.history },
    notif:     { ...(m.premium.notif ?? {}),     ...kv.notif },
    wording:   { ...(m.premium.wording ?? {}),   ...kv.wording },
  })
  fs.writeFileSync(p, JSON.stringify(m, null, 2) + '\n', 'utf8')
  const count = Object.values(kv).reduce((s, o) => s + Object.keys(o).length, 0)
  console.log(`${loc}: +premium.* (${count} keys)`)
}
