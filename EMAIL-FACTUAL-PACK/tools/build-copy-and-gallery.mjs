// EMAIL FACTUAL PACK — generates EMAIL-COPY-VERBATIM.md (from the deterministic renders,
// so no copy is retyped), current-gallery.html and EMAIL-CURRENT-VISUALS.md.
// Run from the repo root: node EMAIL-FACTUAL-PACK/tools/build-copy-and-gallery.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const PACK = 'EMAIL-FACTUAL-PACK'
const DIR  = join(PACK, 'current-renders')
const ids  = readdirSync(DIR).filter((f) => f.endsWith('.json')).map((f) => f.replace(/\.json$/, '')).sort()

const decode = (s) => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, ' ')
const text   = (html) => decode(html.replace(/<br\s*\/?>/gi, '\n').replace(/<\/(p|tr|h2|div|li)>/gi, '\n').replace(/<[^>]+>/g, '')).replace(/[ \t]+/g, ' ').replace(/\n\s*\n+/g, '\n').trim()
const pick   = (re, html) => { const m = html.match(re); return m ? decode(m[1].replace(/<[^>]+>/g, '')).trim() : '' }

const FAMILY = (id) =>
  id.startsWith('AUTH_') || id.startsWith('ACCOUNT_') || id === 'CONSUMER_WELCOME' ? 'A · AUTH / ACCOUNT'
  : id.startsWith('CONSUMER_ORDER') || id === 'PARTNER_NEW_ORDER' ? 'B · CONSUMER ORDER + PARTNER CORE'
  : id.includes('RESERVATION') || id.includes('NOSHOW') ? 'C · RESERVATIONS (sur place — OUT of beta)'
  : id.startsWith('CLAIM_') ? 'D · CLAIMS'
  : id.startsWith('REFUND_') ? 'E · REFUNDS'
  : id.startsWith('ADMIN_') ? 'F · ADMIN / INTERNAL'
  : id.startsWith('PARTNER_') || id.startsWith('COURIER_') || id.startsWith('ONBOARDING_') || id.startsWith('OPERATOR_') || id.startsWith('CREATOR_') ? 'G · PARTNER / ONBOARDING / OPS'
  : 'Z · OTHER'

const rows = ids.map((id) => {
  const meta = JSON.parse(readFileSync(join(DIR, `${id}.json`), 'utf8'))
  const html = readFileSync(join(DIR, `${id}.html`), 'utf8')
  const txt  = existsSync(join(DIR, `${id}.txt`)) ? readFileSync(join(DIR, `${id}.txt`), 'utf8') : null
  const headline = pick(/<h2[^>]*>([\s\S]*?)<\/h2>/i, html)
  const ctas = [...html.matchAll(/<a [^>]*href="([^"]*)"[^>]*>([\s\S]*?)<\/a>/gi)].map((m) => ({ href: m[1], label: decode(m[2].replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim() }))
  const footer = pick(/<p style="font-size:12px;color:#9ca3af[^"]*">([\s\S]*?)<\/p>/i, html)
  const dir = (html.match(/dir="(rtl|ltr)"/) || [])[1] || 'ltr (implicit)'
  return { id, meta, html, txt, headline, ctas, footer, dir, body: text(html) }
})

