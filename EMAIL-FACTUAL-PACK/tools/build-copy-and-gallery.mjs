const flat = (o, p = '') => Object.entries(o || {}).reduce((acc, [k, v]) => (v && typeof v === 'object' ? Object.assign(acc, flat(v, p + k + '.')) : (acc[p + k] = v, acc)), {})
md += `\n## L · Localized families — every key × 5 locales (verbatim from \`messages/*.json\`)\n`
